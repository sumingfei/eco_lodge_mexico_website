/**
 * Scans public/images and writes src/data/images.generated.ts with the
 * intrinsic size and a tiny blur placeholder for every image.
 *
 * Run after adding or replacing photography:
 *   node scripts/generate-image-manifest.mjs
 */
import sharp from "sharp";
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve("public/images");
const OUT = path.resolve("src/data/images.generated.ts");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) files.push(...(await walk(full)));
    else if (/\.(jpe?g|png|webp|avif)$/i.test(e.name)) files.push(full);
  }
  return files.sort();
}

const files = await walk(ROOT);
const entries = [];
for (const file of files) {
  const rel = "/images/" + path.relative(ROOT, file).split(path.sep).join("/");
  const img = sharp(file);
  const meta = await img.metadata();
  const blur = await img.resize(16, 16, { fit: "inside" }).jpeg({ quality: 40 }).toBuffer();
  entries.push({
    src: rel,
    width: meta.width,
    height: meta.height,
    blurDataURL: `data:image/jpeg;base64,${blur.toString("base64")}`,
  });
}

const body = `// AUTO-GENERATED by scripts/generate-image-manifest.mjs — do not edit by hand.
export type ImageMeta = { src: string; width: number; height: number; blurDataURL: string };

export const IMAGE_MANIFEST: Record<string, ImageMeta> = {
${entries.map((e) => `  ${JSON.stringify(e.src)}: ${JSON.stringify(e)},`).join("\n")}
};
`;
await writeFile(OUT, body);
console.log(`Wrote ${entries.length} entries to ${path.relative(process.cwd(), OUT)}`);
